"""Portable exports contain messages and public metadata, never plaintext keys."""
import json
import re
from .engine import Provisioning


def bundle(request: Provisioning, messages: dict) -> dict:
    return {"schema": "she-key-studio/v1", "profile": request.profile, "bank": request.bank,
            "uid": request.uid.hex().upper(), "slot": request.slot, "auth_slot": request.auth_slot,
            "counter": request.counter, "flags": request.flags,
            "messages": {k: v.hex().upper() for k, v in messages.items()}}


def render(request: Provisioning, messages: dict, kind: str = "json", symbol: str = "she_update") -> str:
    if kind == "json":
        return json.dumps(bundle(request, messages), indent=2) + "\n"
    if kind == "text":
        return f"SHE Key Studio | {request.profile} | bank {request.bank}\n" + "\n".join(
            f"{k} ({len(v)} bytes): {v.hex().upper()}" for k, v in messages.items()) + "\n"
    if kind != "c" or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", symbol):
        raise ValueError("C symbol must start with a letter and contain letters, digits, or underscores.")
    lines = ["/* Generated by SHE Key Studio. M4/M5 are EXPECTED proof, not ECU responses. */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, value in messages.items():
        lines.append(f"static const uint8_t {symbol}_{name.lower()}[{len(value)}] = {{")
        for start in range(0, len(value), 8):
            lines.append("    " + ", ".join(f"0x{x:02X}" for x in value[start:start+8]) + ",")
        lines.extend(["};", ""])
    return "\n".join(lines)
